// Cada nivel tiene además una conversación libre que no cuenta para subir de nivel.
for (const level of LEVELS) {
  level.scenarios.push({
    id: `${level.id.toLowerCase()}-free`,
    title: 'Tema libre',
    role: 'Sam, a friendly software developer',
    setting: 'A relaxed call about anything the learner wants: work, technology, hobbies or plans.',
    goal: 'Habla de lo que quieras. Sirve para soltarte sin presión.',
    opener: level.freeOpener,
    phrases: ['I’d like to talk about…', 'What do you think about…?', 'Let me think…', 'Could you repeat that, please?'],
    free: true,
  });
}

export const getLevel = (id) => LEVELS.find((l) => l.id === id) || LEVELS[0];

export function findScenario(scenarioId) {
  for (const level of LEVELS) {
    const scenario = level.scenarios.find((sc) => sc.id === scenarioId);
    if (scenario) return { level, scenario };
  }
  return null;
}

export const gradedScenarios = (level) => level.scenarios.filter((sc) => !sc.free);

// "Emma, a friendly developer…" -> "Emma"
export const roleName = (scenario) => scenario.role.split(',')[0].trim();
